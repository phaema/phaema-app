"""Generated placeholder photos and PDFs for the demonstration estate.

These are drawn by code, not real photographs or real HM Land Registry documents,
and every one is labelled as fictional demonstration material.
"""
from io import BytesIO


def placeholder_photo(label, style="industrial", variant=0):
    """A simple drawn picture of a building, labelled as a demonstration image."""
    from PIL import Image, ImageDraw

    w, h = 1200, 800
    skies = [(186, 214, 235), (205, 222, 236), (226, 232, 238)]
    img = Image.new("RGB", (w, h), skies[variant % 3])
    d = ImageDraw.Draw(img)
    d.rectangle([0, 600, w, h], fill=(120, 130, 120) if style == "land" else (150, 150, 150))
    if style == "industrial":
        d.rectangle([120, 300, 1080, 600], fill=(176, 184, 196), outline=(90, 90, 90), width=4)
        d.polygon([(100, 300), (600, 220), (1100, 300)], fill=(110, 120, 135))
        for i in range(4):
            x = 170 + i * 230
            d.rectangle([x, 400, x + 160, 600], fill=(80, 90, 105) if (i + variant) % 3 else (205, 160, 60))
    elif style == "retail":
        d.rectangle([60, 250, 1140, 600], fill=(196, 160, 132), outline=(90, 70, 60), width=4)
        for i in range(6):
            x = 80 + i * 175
            d.rectangle([x, 450, x + 150, 600], fill=(60, 80, 100))
            d.rectangle([x, 410, x + 150, 445], fill=[(29, 53, 87), (69, 123, 157), (168, 50, 50)][(i + variant) % 3])
            d.rectangle([x + 30, 300, x + 120, 380], fill=(230, 235, 240))
    elif style == "civic":
        d.rectangle([200, 260, 1000, 600], fill=(214, 200, 170), outline=(110, 100, 80), width=4)
        d.polygon([(180, 260), (600, 140), (1020, 260)], fill=(160, 140, 110))
        for i in range(6):
            x = 250 + i * 125
            d.rectangle([x, 320, x + 60, 420], fill=(70, 90, 110))
            d.rectangle([x, 470, x + 60, 570], fill=(70, 90, 110))
        d.rectangle([560, 480, 640, 600], fill=(90, 60, 40))
    else:  # land
        d.rectangle([0, 450, w, 600], fill=(110, 150, 90))
        for i in range(12):
            x = 50 + i * 100
            d.ellipse([x, 380 + (i % 3) * 20, x + 70, 450 + (i % 3) * 20], fill=(70, 110, 60))
    d.rectangle([0, h - 90, w, h], fill=(20, 20, 20))
    d.text((30, h - 75), f"DEMONSTRATION IMAGE - {label}".replace("\u2013", "-"), fill=(255, 255, 255), font_size=34)
    d.text((30, h - 35), "Drawn placeholder, not a photograph. Fictional Exampleton estate.", fill=(220, 220, 220), font_size=22)
    out = BytesIO()
    img.save(out, "PNG")
    return out.getvalue()


def _pdf_escape(text):
    return text.replace("\\", "\\\\").replace("(", "\\(").replace(")", "\\)")


def placeholder_pdf(heading, lines, banner="FICTIONAL DEMONSTRATION DOCUMENT - NOT ISSUED BY HM LAND REGISTRY", more=()):
    """A PDF clearly marked as a fictional demonstration document. One page, plus one for each (heading, lines)
    pair in `more`."""
    foot = ("BT /F1 9 Tf 50 60 Td (Generated by PHAEMA for demonstration and testing. All names, numbers and places "
            "are invented.) Tj ET")
    sheets = [(heading, lines), *more]
    streams = []
    for number, (title, text) in enumerate(sheets, start=1):
        body = [
            f"BT /F2 11 Tf 50 800 Td ({_pdf_escape(banner)}) Tj ET",
            f"BT /F2 18 Tf 50 760 Td ({_pdf_escape(title)}) Tj ET",
        ]
        y = 725
        for line in text:
            body.append(f"BT /F1 11 Tf 50 {y} Td ({_pdf_escape(line)}) Tj ET")
            y -= 18
        body.append(foot)
        if len(sheets) > 1:
            body.append(f"BT /F1 9 Tf 500 60 Td (Page {number} of {len(sheets)}) Tj ET")
        streams.append("\n".join(body).encode("latin-1", "replace"))
    # Objects: 1 catalog, 2 page tree, 3 and 4 fonts, then a page and its content for each sheet.
    kids = " ".join(f"{5 + 2 * i} 0 R" for i in range(len(streams)))
    objects = [
        b"<< /Type /Catalog /Pages 2 0 R >>",
        f"<< /Type /Pages /Kids [{kids}] /Count {len(streams)} >>".encode(),
        b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica /Encoding /WinAnsiEncoding >>",
        b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold /Encoding /WinAnsiEncoding >>",
    ]
    for i, stream in enumerate(streams):
        objects.append(f"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Contents {6 + 2 * i} 0 R "
                       f"/Resources << /Font << /F1 3 0 R /F2 4 0 R >> >> >>".encode())
        objects.append(b"<< /Length " + str(len(stream)).encode() + b" >>\nstream\n" + stream + b"\nendstream")
    out = BytesIO()
    out.write(b"%PDF-1.4\n")
    offsets = []
    for i, obj in enumerate(objects, start=1):
        offsets.append(out.tell())
        out.write(f"{i} 0 obj\n".encode() + obj + b"\nendobj\n")
    xref = out.tell()
    out.write(f"xref\n0 {len(objects) + 1}\n0000000000 65535 f \n".encode())
    for off in offsets:
        out.write(f"{off:010d} 00000 n \n".encode())
    out.write(f"trailer\n<< /Size {len(objects) + 1} /Root 1 0 R >>\nstartxref\n{xref}\n%%EOF\n".encode())
    return out.getvalue()
